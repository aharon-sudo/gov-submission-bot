"""Generate submission email draft"""

from ..models.match_result import MatchResult
from ..models.opportunity import OpportunityData


class EmailGenerator:
    """Generate submission email draft"""

    def generate(self, match_result: MatchResult, opp_data: OpportunityData) -> str:
        """
        Create submission_email.txt

        Args:
            match_result: Match result data
            opp_data: Opportunity data

        Returns:
            Email text content
        """
        lines = []

        # Subject line
        lines.append(f"Subject: Candidate Submission for {opp_data.title}")
        lines.append("")

        # Salutation
        lines.append("Dear Hiring Manager,")
        lines.append("")

        # Introduction
        lines.append(f"Please find our candidate submission for {opp_data.title} (ID: {opp_data.opportunity_id}).")
        lines.append("")

        # Candidate info
        lines.append(f"Candidate: {match_result.candidate_name}")
        lines.append("")

        # Qualification summary
        required_matches = match_result.get_required_matches()
        preferred_matches = match_result.get_preferred_matches()

        required_met = sum(1 for m in required_matches if m.is_met())
        preferred_met = sum(1 for m in preferred_matches if m.is_met())

        required_pct = (required_met / len(required_matches) * 100) if required_matches else 0
        preferred_pct = (preferred_met / len(preferred_matches) * 100) if preferred_matches else 0

        lines.append("Qualification Summary:")
        lines.append(f"- Meets {required_met} of {len(required_matches)} required qualifications ({required_pct:.0f}%)")
        lines.append(f"- Meets {preferred_met} of {len(preferred_matches)} preferred qualifications ({preferred_pct:.0f}%)")
        lines.append("")

        # Key strengths
        strengths = self._get_top_strengths(match_result)
        if strengths:
            lines.append("Key Strengths:")
            for i, match in enumerate(strengths[:3], 1):
                evidence = match.evidence_snippets[0][:100] + "..." if match.evidence_snippets else ""
                lines.append(f"{i}. {match.requirement_text}")
                if evidence:
                    lines.append(f"   - {evidence}")
            lines.append("")

        # Closing
        lines.append("Please review the attached requirements matrix for detailed evidence mapping.")
        lines.append("")
        lines.append("Best regards,")
        lines.append("[Your Organization]")
        lines.append("")

        # Footer
        lines.append("---")
        lines.append("Generated by Gov Submission Bot")
        lines.append("")

        return '\n'.join(lines)

    def _get_top_strengths(self, match_result: MatchResult) -> list:
        """Get top 3 strongest matches"""
        strengths = [
            m for m in match_result.match_results
            if m.is_met() and m.confidence >= 0.8
        ]
        return sorted(strengths, key=lambda m: m.confidence, reverse=True)[:3]
